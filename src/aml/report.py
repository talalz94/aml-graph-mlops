"""Save results as JSON and render the README's two generated blocks: the results table
(generated SYN data is never rendered) and the published baselines."""

from __future__ import annotations

import json
import os
import platform
from datetime import UTC, datetime
from pathlib import Path


def markers(name: str) -> tuple[str, str]:
    return f"<!-- {name}:start -->", f"<!-- {name}:end -->"


START, END = markers("results")
LABELS = {
    "rules-default": "Rules, default thresholds",
    "rules-tuned": "Rules, thresholds tuned per segment",
    "lightgbm": "LightGBM on graph features",
}
# Egressy et al., AAAI 2024, Table 2: minority class F1 (%) on HI-Small. The README's
# baselines block is rendered from this, so these numbers are typed in one place only.
PUBLISHED_HI_SMALL = {
    "XGBoost with graph features": 63.23,
    "LightGBM with graph features": 62.86,
    "GIN": 28.70,
    "PNA": 56.77,
    "Multi-PNA with edge updates": 68.16,
}


def save_result(results_dir: Path, dataset: str, system: str, result: dict) -> Path:
    payload = {
        "dataset": dataset,
        "system": system,
        "label": LABELS[system],
        "command": f"uv run aml eval --system {system} --dataset {dataset}",
        **result,
        "environment": {
            "python": platform.python_version(),
            "os": platform.platform(),
            "logical_cpus": os.cpu_count(),
        },
        "created_utc": datetime.now(UTC).replace(microsecond=0).isoformat(),
    }
    path = results_dir / dataset / f"{system}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
    return path


def load_results(results_dir: Path) -> dict[tuple[str, str], dict]:
    out = {}
    for path in sorted(results_dir.glob("*/*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data["dataset"] != "SYN":
            out[(data["dataset"], data["system"])] = data
    return out


STAMP_KEYS = ("trans_sha256", "period_end", "code_sha256", "package_sha256")


class StaleResults(ValueError):
    """Saved results for one dataset that were not all scored on the same build."""


def check_same_inputs(results: dict[tuple[str, str], dict]) -> None:
    """Every row of a dataset's table must come from the same raw file, feature code,
    package code and test period, or the table would compare unlike things."""
    for dataset in sorted({d for d, _ in results}):
        rows = {s: r for (d, s), r in results.items() if d == dataset}
        build = {
            s: (
                *(r.get("inputs", {}).get(k) for k in STAMP_KEYS),
                r["test_transactions"],
                r["test_laundering"],
            )
            for s, r in rows.items()
        }
        if len(set(build.values())) > 1:
            newest = max(rows, key=lambda s: rows[s].get("created_utc", ""))
            stale = sorted(s for s in rows if build[s] != build[newest])
            raise StaleResults(
                f"{dataset}: {', '.join(stale)} came from another build than {newest}. "
                f"Run `uv run aml reproduce --dataset {dataset}` to score every system again."
            )


def render(results: dict[tuple[str, str], dict]) -> str:
    check_same_inputs(results)
    if not results:
        return (
            "No results yet. They appear here after `uv run aml reproduce` runs on the real "
            "AMLworld data (see Quickstart).\n"
        )
    out = []
    for dataset in sorted({d for d, _ in results}):
        rows = [results[(dataset, s)] for s in LABELS if (dataset, s) in results]
        first = rows[0]
        out += [
            f"**{dataset}, test period** ({first['test_transactions']:,} transactions, "
            f"{first['test_laundering']:,} laundering)",
            "",
            "| System | Minority F1 | PR-AUC | Recall at 50 / 100 / 500 alerts a day "
            "| Alerts (recall) vs tuned rules | Reproduce |",
            "|---|---:|---:|---:|---:|---|",
        ]
        for r in rows:
            b = r["recall_at_budget"]
            a = r["alerts_at_rules_recall"]
            out.append(
                f"| {r['label']} | {100 * r['minority_f1']:.1f} | {100 * r['pr_auc']:.1f} "
                f"| {100 * b['50']:.1f} / {100 * b['100']:.1f} / {100 * b['500']:.1f} "
                f"| {a['alerts']:,} ({100 * a['recall']:.1f}%) vs {a['rules_alerts']:,} "
                f"({100 * a['rules_recall']:.1f}%) | `{r['command']}` |"
            )
        out.append("")
    out += [
        "Generated by `uv run aml report` from `results/`. Do not edit by hand.",
    ]
    return "\n".join(out) + "\n"


def render_baselines() -> str:
    out = [
        "**Published baselines on HI-Small** (minority class F1; Egressy et al., *Provably "
        "Powerful Graph Neural Networks for Directed Multigraphs*, AAAI 2024, Table 2). "
        "Quoted, not reproduced, and not measured on this repo's test set: the paper keeps "
        "the transactions from 11 September 2022 on, which are all laundering, in its test "
        "split, and this repo drops them. Read these as a rough guide, not a like for like "
        "comparison.",
        "",
        "| Model | Minority F1 |",
        "|---|---:|",
        *[f"| {model} | {f1:.2f} |" for model, f1 in PUBLISHED_HI_SMALL.items()],
        "",
        "Generated by `uv run aml report` from `PUBLISHED_HI_SMALL` in `src/aml/report.py`. "
        "Do not edit by hand.",
    ]
    return "\n".join(out) + "\n"


def update_readme(readme: Path, blocks: dict[str, str]) -> bool:
    """Replace the text between each block's markers. Every block's markers must exist."""
    text = readme.read_text(encoding="utf-8")
    updated = text
    for name, block in blocks.items():
        start, end = markers(name)
        i, j = updated.find(start), updated.find(end)
        if i == -1 or j == -1 or j < i:
            raise ValueError(f"{readme} needs {start} and {end} markers")
        updated = updated[: i + len(start)] + "\n" + block + updated[j:]
    if updated == text:
        return False
    readme.write_text(updated, encoding="utf-8", newline="\n")
    return True
